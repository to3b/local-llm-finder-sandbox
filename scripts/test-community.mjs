import fs from 'node:fs';
import assert from 'node:assert/strict';
const file=new URL('../overrides/tests/submissions.js',import.meta.url);
const {normalizeSubmission,parseTestOutput,calibrationCandidates}=await import('data:text/javascript;base64,'+Buffer.from(fs.readFileSync(file,'utf8')).toString('base64'));
const basic={hardware:'NVIDIA GeForce RTX 3060 — 12 GB',model:'Qwen2.5-Coder 7B',hardwareId:'rtx-3060',modelId:'model-10',outcome:'runs'};
const quick=normalizeSubmission({...basic,rawLog:'private prompt and file path',generationTps:24.5,calibrationEligible:true});
assert.equal(quick.calibrationEligible,false);
assert.equal(quick.rawLog,undefined);
assert.equal(quick.contextTokens,null);
assert.equal(quick.runtime,'');
assert.throws(()=>normalizeSubmission({...basic,generationTps:-3}),/positive/);
assert.throws(()=>normalizeSubmission({...basic,outcome:'invented'}),/Choose/);
assert.equal(normalizeSubmission({...basic,outcome:'unable',generationTps:null}).outcome,'unable');
assert.equal(parseTestOutput('prompt eval rate: 900 tokens/s\neval rate: 24.5 tokens/s').generationTps,24.5);
assert.equal(parseTestOutput('prompt processing: 900 tokens/s').recognized,false);
assert.equal(parseTestOutput(JSON.stringify([{n_prompt:512,n_gen:0,avg_ts:900},{n_prompt:0,n_gen:128,avg_ts:25}])).generationTps,25);
assert.equal(parseTestOutput('{"eval_count":128,"eval_duration":4000000000,"response":"private text"}').generationTps,32);
assert.equal(parseTestOutput('not a benchmark').recognized,false);
const run={protocol:'llf-ollama-v1',model:'qwen2.5-coder:7b',modelDigest:'a'.repeat(64),runtimeVersion:'test-version',quant:'Q4_K_M',contextTokens:4096,numPredict:128,offload:'all_on_gpu',samples:[{outputTokens:128,generationSeconds:4,promptTokens:65},{outputTokens:128,generationSeconds:8,promptTokens:65},{outputTokens:128,generationSeconds:4,promptTokens:65}],rawResponse:'private'};
const repeated=normalizeSubmission({...basic,benchmark:run});
assert.equal(repeated.generationTps,32);
assert.equal(repeated.calibrationEligible,true);
assert.equal(repeated.benchmark.rawResponse,undefined);
assert.equal(normalizeSubmission({...basic,benchmark:{...run,offload:'mixed_or_cpu'}}).calibrationEligible,false);
assert.equal(normalizeSubmission({...basic,benchmark:{...run,samples:run.samples.slice(0,2)}}).calibrationEligible,false);
const approved={...repeated,id:'one',useForCalibration:true,verification:'reviewed',_sourceGroup:'source-a'};
assert.deepEqual(calibrationCandidates([{...approved,useForCalibration:false}]),[]);
let groups=calibrationCandidates([approved,{...approved,id:'two'},{...approved,id:'three'}]);
assert.equal(groups[0].sourceCount,1);
assert.equal(groups[0].confidence,'limited evidence');
assert.equal(groups[0].automaticApplication,false);
groups=calibrationCandidates([approved,{...approved,id:'two',benchmark:{...repeated.benchmark,runtimeVersion:'another-version'}}]);
assert.equal(groups.length,2,'Different runtime versions must not be merged');
assert.ok(!JSON.stringify(groups).includes('source-a'),'Private source groups must not be exported');
console.log('Community evidence checks passed: quick reports, generation-only parsing, privacy, repeated-run eligibility and independent-source grouping.');
